import type {
    HistoryEntry,
    HistoryList,
} from "../../../domain/models/history.model";

const isoDaysAgo = (days: number, hour = 9, minute = 0): string => {
    const date = new Date();
    date.setUTCDate(date.getUTCDate() - days);
    date.setUTCHours(hour, minute, 0, 0);
    return date.toISOString();
};

const makeEntry = (
    id: string,
    daysAgo: number,
    goal: string,
    qualityScore: number,
    decision: "accepted" | "best_effort",
    attempts: number,
    durationMs: number,
    resultCount: number,
    collections: string[],
    hour = 9,
    minute = 0,
): HistoryEntry => ({
    id,
    goal,
    query: goal,
    timestamp: isoDaysAgo(daysAgo, hour, minute),
    qualityScore,
    decision,
    attempts,
    durationMs,
    resultCount,
    collectionIds: collections,
});

